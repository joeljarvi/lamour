export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export default async function RootLayout({
  children,
  modal,
  params,
}: Readonly<{
  children: React.ReactNode;
  // @modal slot: the issue modal (intercepted /shop/[slug]), else nothing
  modal: React.ReactNode;
  params: Promise<{ locale: string }>;
}>) {
  const { locale } = await params;
  if (!hasLocale(routing.locales, locale)) notFound();
  setRequestLocale(locale);

  let issues: Issue[] = [];
  let articles: Article[] = [];
  let series: Series[] = [];

  try {
    [issues, articles, series] = await Promise.all([
      client.fetch(issuesQuery),
      client.fetch(articlesQuery),
      client.fetch(seriesQuery),
    ]);
  } catch {
    // Sanity not yet configured
  }

  return (
    <html lang={locale}>
      <body
        className={`${baskerville.variable} ${baskervilleOldFace.variable} ${baskervilleClassic.variable} ${baskervilleSC.variable} ${universTypewriter.variable} ${johnSans.variable} ${baskervilleNeoDisplay.variable} ${baskervilleNeoText.variable} ${unifraktur.variable} antialiased bg-background`}
      >
        <NextIntlClientProvider>
          <CartProvider>
            <IssuesProvider issues={issues}>
              <ArticlesProvider articles={articles} series={series}>
                <QueueProvider>
                  <LLNav />
                  {children}
                  <Footer />
                  {modal}
                </QueueProvider>
              </ArticlesProvider>
              {/* Inside IssuesProvider: looks up each item's image and weight */}
              <CartDrawer />
            </IssuesProvider>
          </CartProvider>
        </NextIntlClientProvider>
      </body>
    </html>
  );
}
