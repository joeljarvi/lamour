import type { Metadata } from "next";
import { Baskervville, Baskervville_SC } from "next/font/google";
import localFont from "next/font/local";
import "./globals.css";
import LLNav from "@/components/LLNav";
import CartDrawer from "@/components/CartDrawer";
import { client } from "@/lib/sanity/client";
import { issuesQuery, articlesQuery, seriesQuery } from "@/lib/sanity/queries";
import { IssuesProvider } from "@/lib/contexts/IssuesContext";
import { ArticlesProvider } from "@/lib/contexts/ArticlesContext";
import { CartProvider } from "@/lib/contexts/CartContext";
import { BookshelfSettingsProvider } from "@/lib/contexts/BookshelfSettingsContext";
import type { Issue } from "@/lib/contexts/IssuesContext";
import type { Article, Series } from "@/lib/contexts/ArticlesContext";

export const revalidate = 3600;

const baskervilleSC = Baskervville_SC({
  variable: "--font-baskervilleSC",
  display: "swap",
  weight: "400",
  subsets: ["latin"],
});

const baskerville = Baskervville({
  variable: "--font-baskerville",
  display: "swap",
  weight: "400",
  subsets: ["latin"],
});

const baskervilleOldFace = localFont({
  src: "./BASKVILL.ttf",
  variable: "--font-baskerville-old-face",
  display: "swap",
});

const baskervilleClassic = localFont({
  src: "./Baskerville-01.ttf",
  variable: "--font-baskervilleClassic",
  display: "swap",
});

const universTypewriter = localFont({
  src: [
    { path: "./UniversNextTypewrtrPro-Rg.ttf", weight: "400", style: "normal" },
    { path: "./UniversNextTypewrtrPro-It.ttf", weight: "400", style: "italic" },
    { path: "./UniversNextTypewrtrPro-Bd.ttf", weight: "700", style: "normal" },
    { path: "./UniversNextTypewrtrPro-BdIt.ttf", weight: "700", style: "italic" },
  ],
  variable: "--font-univers-tw",
  display: "swap",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  let issues: Issue[] = [];
  let articles: Article[] = [];
  let series: Series[] = [];

  try {
    [issues, articles, series] = await Promise.all([
      client.fetch(issuesQuery),
      client.fetch(articlesQuery),
      client.fetch(seriesQuery),
    ]);
  } catch {
    // Sanity not yet configured
  }

  return (
    <html lang="en">
      <body
        className={`${baskerville.variable} ${baskervilleOldFace.variable} ${baskervilleClassic.variable} ${baskervilleSC.variable} ${universTypewriter.variable} antialiased`}
      >
        <CartProvider>
          <BookshelfSettingsProvider>
            <IssuesProvider issues={issues}>
              <ArticlesProvider articles={articles} series={series}>
                <LLNav />
                {children}
              </ArticlesProvider>
            </IssuesProvider>
          </BookshelfSettingsProvider>
          <CartDrawer />
        </CartProvider>
      </body>
    </html>
  );
}
